"""Orchestrate ntqr's exact algebraic evaluation of three error-independent
binary classifiers.

Dataset-agnostic: defaults to the bundled UCI Adult example, but accepts any
registered ``--dataset`` or a ``--dataset-file`` of labeled vote counts (e.g.
the votes generated by ``scripts/llm/``), so the same algebra runs over any
trio of binary classifiers.

Real ntqr methods exercised:
    ntqr.r2.datasketches.TrioLabelVoteCounts.to_TrioVoteCounts
    ntqr.r2.evaluators.ErrorIndependentEvaluation
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import _common  # noqa: E402
import _config  # noqa: E402

_common.ensure_ntqr_importable()

from ntqr.r2.datasketches import TrioLabelVoteCounts  # noqa: E402
from ntqr.r2.evaluators import ErrorIndependentEvaluation  # noqa: E402


def main(argv: list[str] | None = None) -> None:
    config = _config.build_config(
        "ntqr", "error_independent_evaluation", argv=argv
    )
    out = _common.output_dir(config.category, config.name)

    data_sketch = TrioLabelVoteCounts(
        config.load_label_vote_counts()
    ).to_TrioVoteCounts()
    evaluation = ErrorIndependentEvaluation(data_sketch)

    _common.save_json(
        out, "evaluation_exact.json", evaluation.evaluation_exact
    )
    _common.save_json(
        out, "evaluation_float.json", evaluation.evaluation_float
    )
    _common.save_json(
        out,
        "alpha_prevalence_quadratic_terms.json",
        evaluation.alpha_prevalence_quadratic_terms(),
    )

    _common.banner(f"ErrorIndependentEvaluation ({config.dataset})")
    for i, solution in enumerate(evaluation.evaluation_float):
        print(
            f"solution {i}: a-prevalence = {solution['prevalence']['a']:.4f}"
        )
    print(f"-> wrote results to {out}")


if __name__ == "__main__":
    main()
